def _repair_chain(journal: dict) -> dict:
    previous = ledger.header_digest(journal["header"])
    for turn in journal["turns"]:
        turn["prev_turn_digest"] = previous
        previous = ledger.digest(turn)
    return journal


def _detect(journal: dict, sealed_digest: str, keyring) -> dict:
    """Detection from MACs and the out-of-band seal ONLY.

    Chain arithmetic is deliberately not consulted: B8's adversary repairs
    the chain, so a detector that reads it would report success on a journal
    it did not actually catch.
    """

    session_id = journal["header"]["session_id"]
    mac_failures = [
        turn["turn_index"]
        for turn in journal["turns"]
        if not ledger.verify_turn_mac(turn, session_id, keyring)
    ] + [
        record["assumption_id"]
        for record in journal["assumptions"]
        if not ledger.verify_assumption_mac(record, session_id, keyring)
    ]
    file_digest = ledger.text_digest(ledger.serialize(journal))
    return {
        "keyed_mac_detected": bool(mac_failures),
        "mac_failures": mac_failures,
        "out_of_band_seal_detected": file_digest != sealed_digest,
        "detected": bool(mac_failures) or file_digest != sealed_digest,
    }


def score_b8(seal: dict, keyring, seed_string: str) -> dict:
    rng = _rng(seed_string + "-tamper")
    half_b = [entry for entry in seal["sessions"] if entry["half"] == "B"]
    chosen = rng.sample(half_b, 20)
    repaired, naive = [], []
    for entry in chosen:
        original = _journal(entry)
        target = rng.randrange(len(original["turns"]))

        tampered = copy.deepcopy(original)
        tampered["turns"][target]["input_bytes"] = "1 + 1"
        naive_result = _detect(
            tampered, entry["journal_digest"], keyring
        )
        naive.append(
            {
                "session_id": entry["session_id"],
                "turn_index": target,
                **naive_result,
            }
        )

        chained = _repair_chain(copy.deepcopy(tampered))
        chained_result = _detect(chained, entry["journal_digest"], keyring)
        repaired.append(
            {
                "session_id": entry["session_id"],
                "turn_index": target,
                "chain_is_internally_consistent": _chain_consistent(chained),
                **chained_result,
            }
        )

    caught = sum(1 for row in repaired if row["detected"])
    by_mac = sum(1 for row in repaired if row["keyed_mac_detected"])
    floor = REGISTERED_DENOMINATORS["B8"]
    return {
        "verdict": (
            "GREEN"
            if caught == floor and len(repaired) == floor
            else "RED"
        ),
        "registered_denominator": floor,
        "denominator_met": len(repaired) == floor,
        "threat_model": (
            "the tamper script rewrites one turn's bytes AND recomputes every "
            "downstream prev_turn_digest consistently — the naive-chain "
            "repair a file-holding adversary would perform. Detection comes "
            "from the keyed MACs (the tamperer holds no key) or the "
            "out-of-band seal digest, never from chain arithmetic, and the "
            "detector does not read the chain at all."
        ),
        "repaired_chain_arm": {
            "cases": 20,
            "detected": caught,
            "detected_by_keyed_mac": by_mac,
            "rows": repaired,
        },
        "unrepaired_chain_arm": {
            "cases": 20,
            "detected": sum(1 for row in naive if row["detected"]),
            "rows": naive,
            "note": (
                "run and reported, but passing only this arm is not passing "
                "B8 — the design says so and this run does not treat it as a "
                "substitute"
            ),
        },
    }


def _chain_consistent(journal: dict) -> bool:
    previous = ledger.header_digest(journal["header"])
    for turn in journal["turns"]:
        if turn["prev_turn_digest"] != previous:
            return False
        previous = ledger.digest(turn)
    return True


