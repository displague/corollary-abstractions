def score_b2(seal: dict, pins: dict, index) -> dict:
    started = time.time()
    per_session = []
    reproduced = total = 0
    for entry in seal["sessions"]:
        report = replay_session.replay(
            REPO, _journal(entry), shared_index=index, live_pins=pins
        )
        total += report.turns_total
        reproduced += report.turns_reproduced
        per_session.append(
            {
                "session_id": entry["session_id"],
                "half": entry["half"],
                "turns_total": report.turns_total,
                "turns_reproduced": report.turns_reproduced,
                "first_divergence_turn": report.first_divergence_turn,
                "divergences": report.divergences,
            }
        )
    elapsed = round(time.time() - started, 1)
    misses = [row for row in per_session if row["first_divergence_turn"] is not None]
    return {
        "verdict": "GREEN" if not misses else "RED",
        "denominator": total,
        "denominator_source": "the seal's own turn count, not a round number",
        "turns_reproduced": reproduced,
        "misses_published_individually": misses,
        "elapsed_seconds": elapsed,
        "budget_seconds": 1800,
        "overrun": elapsed > 1800,
        "by_half": {
            half: {
                "turns_total": sum(
                    row["turns_total"] for row in per_session
                    if row["half"] == half
                ),
                "turns_reproduced": sum(
                    row["turns_reproduced"] for row in per_session
                    if row["half"] == half
                ),
            }
            for half in ("A", "B")
        },
    }


def score_b3(seal: dict, pins: dict, index) -> dict:
    """Every pin, every journal, no sampling."""

    results = []
    for entry in seal["sessions"]:
        journal = _journal(entry)
        for field in ledger.PIN_FIELDS:
            perturbed = dict(pins)
            perturbed[field] = f"perturbed-{field}"
            report = replay_session.replay(
                REPO, journal, shared_index=index, live_pins=perturbed
            )
            ok = (
                report.refusal == replay_session.STALE
                and report.pin_mismatch == [field]
                and report.turns_reproduced == 0
            )
            if not ok:
                results.append(
                    {
                        "session_id": entry["session_id"],
                        "pin": field,
                        "refusal": report.refusal,
                        "pin_mismatch": report.pin_mismatch,
                        "turns_reproduced": report.turns_reproduced,
                    }
                )
    total = len(seal["sessions"]) * len(ledger.PIN_FIELDS)
    return {
        "verdict": "GREEN" if not results else "RED",
        "perturbations": total,
        "pins": list(ledger.PIN_FIELDS),
        "sampling": "none — every pin field on every sealed journal",
        "failures": results,
    }


