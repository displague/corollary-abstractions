def b13_draw(seal: dict, seed_string: str) -> list[dict]:
    rng = _rng(seed_string)
    pool = []
    for entry in seal["sessions"]:
        if entry["half"] != "B":
            continue
        journal = _journal(entry)
        assumptions = {
            record["assumption_id"]: record
            for record in journal["assumptions"]
        }
        for turn in journal["turns"]:
            if not ledger.is_binding_dependent(turn):
                continue
            pool.append(
                {
                    "session_id": entry["session_id"],
                    "turn_index": turn["turn_index"],
                    "input_bytes": turn["input_bytes"],
                    "cited": turn["assumptions_cited"],
                    "cited_normal_forms": [
                        assumptions[item]["normal_form"]
                        for item in turn["assumptions_cited"]
                    ],
                }
            )
    pool.sort(key=lambda row: (row["session_id"], row["turn_index"]))
    drawn = rng.sample(pool, 20)
    rng.shuffle(drawn)
    for position, row in enumerate(drawn):
        row["audit_case"] = f"c{position:02d}"
    return drawn


