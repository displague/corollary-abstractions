def score_b7(seal: dict) -> dict:
    misses, total = [], 0
    for entry in seal["sessions"]:
        for turn in _journal(entry)["turns"]:
            if turn["result"]["kind"] not in ledger.REFUSAL_STATUSES:
                continue
            total += 1
            if not turn["receipt_digest"] or turn["assumptions_cited"] is None:
                misses.append(
                    {
                        "session_id": entry["session_id"],
                        "turn_index": turn["turn_index"],
                        "receipt_digest": turn["receipt_digest"],
                        "assumptions_cited": turn["assumptions_cited"],
                    }
                )
    return {
        "verdict": "GREEN" if not misses else "RED",
        "refusal_turns": total,
        "misses": misses,
        "empty_is_allowed_null_is_red": True,
    }


def score_b10(seal: dict, index) -> dict:
    misses, total = [], 0
    for entry in seal["sessions"]:
        journal = _journal(entry)
        for turn in journal["turns"]:
            if turn["assumptions_cited"]:
                continue
            total += 1
            fresh = CoreSession.boot(
                REPO, offline=True, session_id=entry["session_id"]
            )
            fresh.resolver_index = index
            verdict = route_line(REPO, fresh, turn["input_bytes"])
            if ledger.answer_bytes_digest(verdict) != (
                turn["result"]["answer_bytes_digest"]
            ):
                misses.append(
                    {
                        "session_id": entry["session_id"],
                        "turn_index": turn["turn_index"],
                        "input_bytes": turn["input_bytes"],
                    }
                )
    return {
        "verdict": "GREEN" if not misses else "RED",
        "uncited_turns": total,
        "misses": misses,
    }


def score_b12(seal: dict) -> dict:
    misses, total = [], 0
    for entry in seal["sessions"]:
        journal = _journal(entry)
        log = _read_log(entry)
        from_log: dict[int, set[str]] = {}
        for event in log["events"]:
            from_log.setdefault(event["turn_index"], set()).add(
                event["assumption_id"]
            )
        for turn in journal["turns"]:
            total += 1
            claimed = set(turn["assumptions_cited"])
            corroborated = from_log.get(turn["turn_index"], set())
            if claimed != corroborated:
                misses.append(
                    {
                        "session_id": entry["session_id"],
                        "turn_index": turn["turn_index"],
                        "journal_says": sorted(claimed),
                        "read_log_says": sorted(corroborated),
                    }
                )
    return {
        "verdict": "GREEN" if not misses else "RED",
        "turns_checked": total,
        "uncorroborated": misses,
        "how_the_two_sides_are_independent": (
            "the journal's citation list is a per-turn snapshot taken by "
            "session_ledger.write_journal's caller at turn close; the read "
            "log is written by session_ledger.write_read_log from the "
            "barrier's raw event list. Different functions, different files."
        ),
    }


