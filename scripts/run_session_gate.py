def _rng(seed_string: str) -> random.Random:
    """The prereg's frozen derivation, written out there and applied here."""

    return random.Random(
        int(hashlib.sha256(seed_string.encode("utf-8")).hexdigest()[:16], 16)
    )


def _load(path: str) -> dict:
    return json.loads((REPO / path).read_text(encoding="utf-8"))


def _journal(entry: dict) -> dict:
    return json.loads((REPO / entry["journal"]).read_text(encoding="utf-8"))


def _read_log(entry: dict) -> dict:
    return json.loads((REPO / entry["read_log"]).read_text(encoding="utf-8"))


