def run(repo_root: Path) -> dict:
    from resolver import default_index  # noqa: PLC0415
    from session_keys import SessionKeyRing  # noqa: PLC0415

    prereg = _load(PREREG)
    seal = _load(SEAL)
    seeds = prereg["blind_control"]["seeds_frozen_now"]
    index = default_index()
    keyring = SessionKeyRing.open(repo_root / ".runtime" / "session-keys.json")

    boot = CoreSession.boot(repo_root, offline=True)
    pins = ledger.pins(repo_root, boot.matrix)

    started = time.time()
    b1 = score_b1(seal)
