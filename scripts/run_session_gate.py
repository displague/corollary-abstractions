def _case_id(payload: dict) -> str:
    return hashlib.sha256(ledger.canonical(payload).encode("utf-8")).hexdigest()[:16]


def build_cases(seal: dict, seed_string: str) -> tuple[list[dict], dict]:
    """One mixer, three arms, and the arm labels kept in a separate object.

    Returns `(cases, key)`. `cases` carries no arm field and is shuffled;
    `key` maps `case_id` to arm and is not consulted until after scoring.
    """

    rng = _rng(seed_string)
    cases: list[dict] = []
    key: dict[str, str] = {}
    half_b = [entry for entry in seal["sessions"] if entry["half"] == "B"]

    def _add(arm: str, payload: dict) -> None:
        case_id = _case_id(payload)
        cases.append({"case_id": case_id, **payload})
        key[case_id] = arm

    # --- B4: mutate one CITED assumption on each binding-dependent turn ---
    for entry in half_b:
        journal = _journal(entry)
        for turn in journal["turns"]:
            if not ledger.is_binding_dependent(turn):
                continue
            assumption_id = turn["assumptions_cited"][0]
            record = next(
                item
                for item in journal["assumptions"]
                if item["assumption_id"] == assumption_id
            )
            atom, polarity = record["normal_form"]
            flip = rng.random() < 0.5
            if flip:
                new_atom, new_polarity = atom, not polarity
                new_text = ("not " + atom) if polarity else atom
            else:
                name, value = atom.split("=", 1)
                new_value = int(value.strip()) + 1 + rng.randrange(3)
                new_atom = f"{name.strip()} = {new_value}"
                new_polarity = polarity
                new_text = new_atom if polarity else f"not {new_atom}"
            _add(
                "B4",
                {
                    "session_id": entry["session_id"],
                    "watch_turn": turn["turn_index"],
                    "mutation": {
                        "kind": "edit",
                        "assumption_id": assumption_id,
                        "text_bytes": new_text,
                        "normal_form": [new_atom, new_polarity],
                    },
                },
            )

    # --- B5: 60 sham assumptions, well formed and never cited -------------
    for number in range(60):
        entry = half_b[number % len(half_b)]
        journal = _journal(entry)
        watch = journal["turns"][number % len(journal["turns"])]["turn_index"]
        name = f"sham{number:02d}"
        _add(
            "B5",
            {
                "session_id": entry["session_id"],
                "watch_turn": watch,
                "mutation": {
                    "kind": "insert",
                    "record": {
                        "assumption_id": f"s{number:03d}",
                        "declared_at_turn": 0,
                        "text_bytes": f"{name} = {number}",
                        "normal_form": [f"{name} = {number}", True],
                        "status": "live",
                        "superseded_by": None,
                        "key_id": "",
                        "mac": "",
                    },
                },
            },
        )

    # --- B6: mutate a LIVE BUT UNCITED assumption, watching one turn ------
    #
    # Up to B6_PER_SESSION cases per half-B session. The first version of
    # this generator took at most ONE, and half B holds 25 sessions, so its
    # ceiling was 25 against a registered floor of >=30 — a generator whose
    # ceiling sits below the floor it feeds, which is §4.0(3)'s
    # unmeetable-floor defect appearing inside the instrument. It produced
    # 21 and the run reported B6 green anyway, because it checked flips and
    # never checked its own denominator. Both halves of that are fixed here
    # and the original run stands unedited (prereg amendment 2).
    for entry in half_b:
        journal = _journal(entry)
        ids = [item["assumption_id"] for item in journal["assumptions"]]
        taken = 0
        for turn in journal["turns"]:
            if taken >= B6_PER_SESSION:
                break
            uncited = [
                item
                for item in ids
                if item not in turn["assumptions_cited"]
                and _declared_by(journal, item) <= turn["turn_index"]
            ]
            if not uncited:
                continue
            assumption_id = uncited[rng.randrange(len(uncited))]
            record = next(
                item
                for item in journal["assumptions"]
                if item["assumption_id"] == assumption_id
            )
            atom, polarity = record["normal_form"]
            if "=" not in atom:
                continue
            name, value = atom.split("=", 1)
            new_atom = f"{name.strip()} = {int(value.strip()) + 7}"
            _add(
                "B6",
                {
                    "session_id": entry["session_id"],
                    "watch_turn": turn["turn_index"],
                    "mutation": {
                        "kind": "edit",
                        "assumption_id": assumption_id,
                        "text_bytes": new_atom if polarity else f"not {new_atom}",
                        "normal_form": [new_atom, polarity],
                    },
                },
            )
            taken += 1
    rng.shuffle(cases)
    return cases, key


def _declared_by(journal: dict, assumption_id: str) -> int:
    for item in journal["assumptions"]:
        if item["assumption_id"] == assumption_id:
            return item["declared_at_turn"]
    return 1 << 30


def _apply(journal: dict, mutation: dict) -> dict:
    """Build the mutated FIXTURE. Never written under experiments/sessions/.

    B4's rule, obeyed for every arm: only the Assumption record moves. No
    turn's `input_bytes` is touched by anything here, which is what makes
    the stateless baseline's score-zero a construction rather than a hope.
    """

    fixture = copy.deepcopy(journal)
    if mutation["kind"] == "insert":
        fixture["assumptions"].append(copy.deepcopy(mutation["record"]))
        return fixture
    for record in fixture["assumptions"]:
        if record["assumption_id"] == mutation["assumption_id"]:
            record["text_bytes"] = mutation["text_bytes"]
            record["normal_form"] = list(mutation["normal_form"])
    return fixture


def score_cases(
    seal: dict, cases: list[dict], pins: dict, index, *, stateless: bool = False
) -> list[dict]:
    """Blind scoring: no case carries an arm and none is looked up."""

    by_id = {entry["session_id"]: entry for entry in seal["sessions"]}
    baseline: dict[str, dict] = {}
    scored = []
    for case in cases:
        entry = by_id[case["session_id"]]
        journal = _journal(entry)
        if case["session_id"] not in baseline:
            baseline[case["session_id"]] = {
                turn["turn_index"]: turn["result"]["answer_bytes_digest"]
                for turn in journal["turns"]
            }
        fixture = _apply(journal, case["mutation"])
        report = replay_session.replay(
            REPO,
            fixture,
            shared_index=index,
            live_pins=pins,
            stateless=stateless,
        )
        watched = [
            item
            for item in report.divergences
            if item["turn_index"] == case["watch_turn"]
        ]
        scored.append(
            {
                "case_id": case["case_id"],
                "session_id": case["session_id"],
                "watch_turn": case["watch_turn"],
                "flipped": bool(watched),
                "replayed_status": watched[0]["replayed_status"] if watched else None,
                "replayed_route": watched[0]["replayed_route"] if watched else None,
            }
        )
    return scored


