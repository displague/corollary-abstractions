def score_b13(draw: list[dict]) -> dict:
    """The audit's table. Marks are read from a committed file, never guessed."""

    path = REPO / AUDIT_MARKS
    if not path.exists():
        return {
            "verdict": "NOT YET MARKED",
            "drawn": draw,
            "marked_yes": 0,
            "why": (
                f"the draw is published in {AUDIT_MARKS}'s absence; the "
                "auditor marks each case and the run is re-read"
            ),
        }
    marks = json.loads(path.read_text(encoding="utf-8"))
    by_case = {row["audit_case"]: row for row in marks["marks"]}
    table = []
    for row in draw:
        mark = by_case.get(row["audit_case"], {})
        table.append({**row, "meaning_depends": mark.get("meaning_depends"),
                      "auditor_note": mark.get("note")})
    yes = sum(1 for row in table if row["meaning_depends"] is True)
    return {
        "verdict": "GREEN" if yes >= 16 else "BELOW FLOOR",
        "floor": 16,
        "of": 20,
        "marked_yes": yes,
        "table": table,
        "auditor": marks["auditor"],
        "auditor_independence": marks["auditor_independence"],
        "what_below_the_floor_would_mean": (
            "§11's cited-but-inert residual is promoted from named to "
            "measured against the claim, and the served line carries it"
        ),
        "and_the_limitation_of_an_easy_audit": marks["limitation"],
    }


def _self_digest() -> str:
    payload = Path(__file__).read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(payload).hexdigest()


