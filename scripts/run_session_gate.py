def _baseline_b2(seal: dict, pins: dict, index) -> dict:
    rows = []
    for entry in seal["sessions"]:
        journal = _journal(entry)
        if any(journal["assumptions"]):
            continue
        report = replay_session.replay(
            REPO, journal, stateless=True, shared_index=index, live_pins=pins
        )
        rows.append(
            {
                "session_id": entry["session_id"],
                "turns_total": report.turns_total,
                "turns_reproduced": report.turns_reproduced,
            }
        )
    ok = all(row["turns_reproduced"] == row["turns_total"] for row in rows)
    return {
        "verdict": "GREEN" if ok and rows else "RED",
        "assumption_free_sessions": len(rows),
        "rows": rows,
    }


