def _first_commit(path: str) -> str:
    out = subprocess.run(
        ["git", "log", "--diff-filter=A", "--format=%H %cI", "--", path],
        cwd=REPO,
        capture_output=True,
        text=True,
    )
    lines = [line for line in out.stdout.splitlines() if line.strip()]
    return lines[-1] if lines else ""


def score_b1(seal: dict) -> dict:
    """B1, both clauses, adjudicated separately because they differ in kind.

    Clause 2 — *any edit to a sealed journal or the seal voids the run* — is
    mechanical and is checked against the seal's own digests.

    Clause 1 — *P3's seal exists before the replayer is written* — is an
    ORDERING claim, and this run does not meet it as literally registered.
    The order is published rather than reinterpreted: the commission that
    built this slice put the machinery (including `scripts/replay_session.py`)
    before the recording, so the replayer was committed while
    `experiments/sessions/` did not exist.

    What that costs, stated in both directions rather than only the
    convenient one. B1's order protects against a replayer FITTED TO a
    frozen corpus. The order actually taken gives that protection in a
    stronger form — the replayer could not be fitted to journals that did
    not exist — and gives up the mirror protection, that a corpus not be
    authored to suit an existing replayer. The corpus WAS authored after the
    replayer, by the same hand, so that exposure is real and is the honest
    finding here. Its mitigations are named and none of them is a
    substitute: the authoring script is committed and its six shapes are
    declared; the shapes are assigned by counter, not by half; and the
    replayer's own bytes have not changed since before the corpus existed,
    which git can confirm.
    """

    journal_edits = []
    for entry in seal["sessions"]:
        for key, digest_field in (
            ("journal", "journal_digest"),
            ("read_log", "read_log_digest"),
        ):
            path = REPO / entry[key]
            got = ledger.text_digest(path.read_text(encoding="utf-8"))
            if got != entry[digest_field]:
                journal_edits.append(
                    {
                        "session_id": entry["session_id"],
                        "file": entry[key],
                        "sealed": entry[digest_field],
                        "found": got,
                    }
                )

    replayer = _first_commit("scripts/replay_session.py")
    seal_commit = _first_commit(SEAL)
    return {
        "clause_2_no_sealed_file_was_edited": {
            "verdict": "GREEN" if not journal_edits else "RED",
            "files_checked": 2 * len(seal["sessions"]),
            "edits_found": journal_edits,
        },
        "clause_1_seal_before_replayer": {
            "verdict": "MISSED",
            "replayer_first_committed": replayer,
            "seal_first_committed": seal_commit,
            "what_happened": (
                "the replayer was committed before the seal existed, because "
                "this slice's ordered work put the machinery before the "
                "recording"
            ),
            "what_it_protects_and_what_it_gave_up": (
                "B1's order guards against a replayer fitted to a frozen "
                "corpus; the order taken gives that in a stronger form (the "
                "replayer could not be fitted to journals that did not "
                "exist) and gives up the mirror guard, that a corpus not be "
                "authored to suit an existing replayer. The corpus WAS "
                "authored after the replayer by the same hand. That exposure "
                "is real and is published rather than argued away."
            ),
            "mitigations_that_are_not_substitutes": [
                "the authoring script is committed and its six shapes are "
                "declared in its docstring",
                "shapes are assigned by counter, so the authoring consulted "
                "nothing about which half a session would land in",
                "the replayer's bytes have not changed since before the "
                "corpus existed, and git can confirm it",
            ],
            "does_it_void_the_run": (
                "no, and the reason is registered rather than chosen now: B1 "
                "is not in R1 (§9) and not among §11's stop conditions. The "
                "miss is adjudicated and published, which is what the release "
                "gate asks of B1-B13, and no clause is claimed green that is "
                "not."
            ),
        },
    }


