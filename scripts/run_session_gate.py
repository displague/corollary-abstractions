#!/usr/bin/env python3
"""The registered run — B1-B8, B10-B13, the controls, and R1.

`docs/DESIGN-session-ledger.md` §7 is the construction gate, §8 is the blind
control and the voiding sentence, §9 is R1. The numbers were frozen in the
design before this file existed and re-frozen verbatim in
`experiments/session_ledger_prereg.json`; this script scores them and writes
`experiments/session_ledger_run.json`.

**Half B's first execution is the registered run.** Half A is available for
debugging and is scored beside half B wherever a clause is corpus-wide, but
the verdicts that license anything are half B's.

## The mixer is sealed and the scorer is blind

§8: *"Mutations for B4/B5/B6 are generated by one sealed script mixing the
three arms; the scorer sees no arm labels until after scoring."* That is
mechanical here, not a promise. :func:`build_cases` returns two objects — a
shuffled case list carrying an opaque `case_id` and **no arm field**, and a
separate key mapping `case_id` to its arm. :func:`score_cases` is handed only
the first, records only `(case_id, flipped?, replayed status)`, and the join
against the key is the last step of the run. The seed is the string frozen
in the prereg.

Every case has the same shape whatever arm it belongs to — a journal
mutation and one turn to watch — so the scorer cannot infer an arm from the
case's structure either. A blindness that a scorer could see through by
looking at a field name would be ceremony.

## What this run does not do

It does not decide whether any answer was right. §10: *sessions are
reproducible, not correct, and a wrong answer replays as faithfully as a
right one.* Every verdict below is about bytes.
"""

